//! Release updates from GitHub, standalone (no workspace dependencies).
//!
//! Every release publishes, per platform, a manifest `update-<platform>.json` with a detached
//! ed25519 signature `update-<platform>.json.sig` and the payload `codecraft-payload-<version>-
//! <platform>.tar.gz`. The app fetches the manifest from the repository's latest release, checks
//! the signature against the public key built into the binary, and only then trusts anything in
//! it: the version (must be newer than the running one), the asset URL (must be a release asset of
//! this repository) and the payload's size and SHA-256. The payload is unpacked with a strict
//! extractor. Installing the unpacked payload is the version store's job (`codecraft-selfupdate`).
//!
//! The private key never leaves the machine that builds releases (`cargo xtask update-keygen`).
#![deny(clippy::indexing_slicing, clippy::string_slice)]

mod fetch;
mod pack;
mod sign;
mod version;

pub use fetch::{Fetch, Http};
pub use pack::{pack, unpack};
pub use sign::{generate_secret, public_key, sign};
pub use version::Version;

use base64::Engine;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::io::Write;
use std::path::{Path, PathBuf};

/// The repository releases are published to.
pub const DEFAULT_REPO: &str = "Saimirbaci/codecraft";
/// The release signing key (base64 of the 32-byte ed25519 public key), generated by
/// `cargo xtask update-keygen`.
pub const PUBLIC_KEY: &str = include_str!("../update.pub");
/// The manifest format this build understands.
pub const FORMAT: u32 = 1;
/// A manifest or signature is a few hundred bytes; anything bigger is not one.
const MANIFEST_LIMIT: u64 = 64 * 1024;
/// Payloads are an app binary (tens of MB); refuse absurd downloads.
pub const PAYLOAD_LIMIT: u64 = 1024 * 1024 * 1024;

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("network: {0}")]
    Network(String),
    #[error("invalid update: {0}")]
    Invalid(String),
    #[error("update signature does not verify: {0}")]
    Signature(String),
    #[error("io: {0}")]
    Io(#[from] std::io::Error),
}
pub type Result<T> = std::result::Result<T, Error>;

pub(crate) fn invalid(msg: impl Into<String>) -> Error {
    Error::Invalid(msg.into())
}

/// Where to look and whom to trust. `release()` is the production configuration; tests point
/// `base_url` at a local server and use their own key.
#[derive(Clone, Debug)]
pub struct Config {
    /// Directory URL holding `update-<platform>.json[.sig]` (the latest release's downloads).
    pub base_url: String,
    /// Asset URLs in a manifest must start with this.
    pub asset_prefix: String,
    pub public_key: [u8; 32],
}

impl Config {
    pub fn release() -> Self {
        Self::for_repo(DEFAULT_REPO)
    }
    pub fn for_repo(repo: &str) -> Self {
        Self {
            base_url: format!("https://github.com/{repo}/releases/latest/download"),
            asset_prefix: format!("https://github.com/{repo}/releases/download/"),
            public_key: decode_key(PUBLIC_KEY).unwrap_or([0; 32]),
        }
    }
}

pub(crate) fn decode_key(text: &str) -> Option<[u8; 32]> {
    let bytes = base64::engine::general_purpose::STANDARD.decode(text.trim()).ok()?;
    bytes.try_into().ok()
}

/// `macos-aarch64`, `linux-x86_64`, `windows-x86_64`, …
pub fn platform() -> String {
    format!("{}-{}", std::env::consts::OS, std::env::consts::ARCH)
}

/// The signed description of one platform's payload for one release.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Manifest {
    pub format: u32,
    pub version: String,
    pub commit: String,
    pub platform: String,
    pub url: String,
    pub sha256: String,
    pub size: u64,
    /// The oldest stable launcher that can start this payload (empty: any).
    #[serde(default)]
    pub min_launcher: String,
    #[serde(default)]
    pub notes: String,
}

/// File names a release uses for `platform`.
pub fn manifest_name(platform: &str) -> String {
    format!("update-{platform}.json")
}
pub fn payload_name(version: &str, platform: &str) -> String {
    format!("codecraft-payload-{version}-{platform}.tar.gz")
}

pub enum Check {
    UpToDate,
    Available(Manifest),
}

/// Fetch and verify the latest release's manifest for this platform and compare it with
/// `current`. A manifest that is not newer is `UpToDate` (never a downgrade).
pub fn check(cfg: &Config, fetch: &dyn Fetch, current: &str) -> Result<Check> {
    let platform = platform();
    let name = manifest_name(&platform);
    let body = fetch_small(fetch, &format!("{}/{name}", cfg.base_url))?;
    let sig = fetch_small(fetch, &format!("{}/{name}.sig", cfg.base_url))?;
    let manifest = verify(cfg, &body, &sig)?;
    if manifest.platform != platform {
        return Err(invalid(format!("manifest is for {}, this is {platform}", manifest.platform)));
    }
    let candidate = Version::parse(&manifest.version).ok_or_else(|| invalid("manifest version is not a version"))?;
    let running = Version::parse(current).ok_or_else(|| invalid("running version is not a version"))?;
    Ok(if candidate > running { Check::Available(manifest) } else { Check::UpToDate })
}

fn fetch_small(fetch: &dyn Fetch, url: &str) -> Result<Vec<u8>> {
    let mut out = Vec::new();
    fetch.get(url, MANIFEST_LIMIT, &mut out)?;
    Ok(out)
}

/// Check the detached signature over exactly `body`, then parse and sanity-check it.
pub fn verify(cfg: &Config, body: &[u8], sig: &[u8]) -> Result<Manifest> {
    sign::verify(&cfg.public_key, body, sig)?;
    let manifest: Manifest = serde_json::from_slice(body).map_err(|e| invalid(format!("manifest: {e}")))?;
    if manifest.format != FORMAT {
        return Err(invalid(format!("manifest format {} is not supported (expected {FORMAT})", manifest.format)));
    }
    if !manifest.url.starts_with(&cfg.asset_prefix) || manifest.url.contains(['\n', '\r', ' ']) {
        return Err(invalid("asset URL is not a release asset of this repository"));
    }
    let hex = |s: &str, n: usize| s.len() == n && s.bytes().all(|b| b.is_ascii_hexdigit());
    if !hex(&manifest.sha256, 64) {
        return Err(invalid("sha256 is not 64 hex digits"));
    }
    if !(4..=64).contains(&manifest.commit.len()) || !manifest.commit.bytes().all(|b| b.is_ascii_hexdigit()) {
        return Err(invalid("commit is not a hex id"));
    }
    if manifest.size == 0 || manifest.size > PAYLOAD_LIMIT {
        return Err(invalid("payload size out of range"));
    }
    Ok(manifest)
}

/// Download the payload into `dir`, checking size and SHA-256 as it streams. Returns the file.
pub fn download(fetch: &dyn Fetch, manifest: &Manifest, dir: &Path) -> Result<PathBuf> {
    std::fs::create_dir_all(dir)?;
    let path = dir.join(payload_name_for(manifest));
    let mut sink = HashingFile { file: std::fs::File::create(&path)?, hash: Sha256::new(), bytes: 0 };
    let result = fetch.get(&manifest.url, manifest.size, &mut sink);
    let HashingFile { file, hash, bytes } = sink;
    drop(file);
    let verdict = result.and_then(|()| {
        if bytes != manifest.size {
            return Err(invalid(format!("downloaded {bytes} bytes, expected {}", manifest.size)));
        }
        let digest = hex(&hash.finalize());
        if !digest.eq_ignore_ascii_case(&manifest.sha256) {
            return Err(invalid("downloaded payload does not match the signed SHA-256"));
        }
        Ok(())
    });
    if let Err(e) = verdict {
        let _ = std::fs::remove_file(&path);
        return Err(e);
    }
    Ok(path)
}

fn payload_name_for(manifest: &Manifest) -> String {
    // Never trust the manifest for a path: the name is rebuilt from validated pieces.
    let safe = |s: &str| s.chars().filter(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_')).collect::<String>();
    payload_name(&safe(&manifest.version), &safe(&manifest.platform))
}

pub(crate) fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

struct HashingFile {
    file: std::fs::File,
    hash: Sha256,
    bytes: u64,
}
impl Write for HashingFile {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.file.write_all(buf)?;
        self.hash.update(buf);
        self.bytes = self.bytes.saturating_add(buf.len() as u64);
        Ok(buf.len())
    }
    fn flush(&mut self) -> std::io::Result<()> {
        self.file.flush()
    }
}

/// SHA-256 of a file, lower-case hex.
pub fn sha256_file(path: &Path) -> Result<String> {
    let mut file = std::fs::File::open(path)?;
    let mut hash = Sha256::new();
    std::io::copy(&mut file, &mut HashWriter(&mut hash))?;
    Ok(hex(&hash.finalize()))
}
struct HashWriter<'a>(&'a mut Sha256);
impl Write for HashWriter<'_> {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.0.update(buf);
        Ok(buf.len())
    }
    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}
