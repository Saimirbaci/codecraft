//! The VS Code and Emacs keymaps (Settings › Keymap), built from those editors' public
//! default-keybinding references, only for actions CodeCraft has:
//!
//! - VS Code: the "Keyboard shortcuts for macOS" and "… for Windows" / "… for Linux" reference
//!   sheets published by Microsoft (code.visualstudio.com/docs/getstarted/keybindings, linked
//!   PDFs) and the default keybindings listed there.
//! - Emacs: the GNU Emacs Reference Card (gnu.org, `etc/refcards/refcard.pdf` in the Emacs
//!   sources); Meta is `Alt`.
//!
//! No JetBrains keymap files were read. Each keymap lists its own bindings; every other command
//! keeps its parent keymap's shortcuts, minus those that clash with a key listed here (see
//! [`crate::keymaps::defaults`]). Sources are also noted in `docs/keymaps.md`.

/// A derived keymap: (name, parent keymap, command → shortcuts).
pub type DerivedKeymap = (&'static str, &'static str, &'static [(&'static str, &'static [&'static str])]);

pub const DERIVED: &[DerivedKeymap] = &[
    (crate::keymaps::VSCODE_MAC, crate::keymaps::MACOS, VSCODE_MAC),
    (crate::keymaps::VSCODE, crate::keymaps::WINDOWS_LINUX, VSCODE_PC),
    (crate::keymaps::EMACS, crate::keymaps::WINDOWS_LINUX, EMACS),
];

